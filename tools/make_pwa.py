# Builds the installable-offline layer of the site: the PWA icons (from the Android launcher icon), the web app
# manifest and the service worker with its precache list. Run from the repository root after changing the site's
# static files, and commit what it writes:
#
#     python tools/make_pwa.py
#
# The firmware and data JSONs are not precached: the worker caches them as they are fetched (network first), so the
# sync-firmware workflow's commits keep working without regenerating this.
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "static"

PAGES = [
    "index.html", "flash/index.html", "codeplug/index.html",
    "en/index.html", "en/flash/index.html", "en/codeplug/index.html",
]
RUNTIME_ONLY = ("downloads/", "firmware/")  # cached on fetch, never precached


def icons():
    try:
        from PIL import Image
    except ImportError:
        print("PIL missing: icons left as they are")
        return
    src = ROOT / "android/app/src/main/res/drawable-nodpi/ic_launcher.png"
    if not src.is_file():
        print("no launcher icon: icons left as they are")
        return
    img = Image.open(src).convert("RGBA")
    for size in (192, 512):
        out = STATIC / "img" / f"icon-{size}.png"
        img.resize((size, size), Image.LANCZOS).save(out)
        print("icon", out.relative_to(ROOT))


def precache_list():
    out = list(PAGES)
    for base in (STATIC, ROOT / "data", ROOT / "firmware"):
        for p in sorted(base.rglob("*")):
            if not p.is_file():
                continue
            rel = p.relative_to(ROOT).as_posix()
            if rel.startswith(RUNTIME_ONLY):
                continue
            q = f"?v={hashlib.sha256(p.read_bytes()).hexdigest()[:10]}"
            out.append(rel + (q if rel.startswith("static/") else ""))
    return out


def manifest(entries):
    doc = {
        "name": "DM32 Web CPS & Flasher",
        "short_name": "DM32 CPS",
        "description": "Flash the DM-32UV and edit its codeplug in the browser. Works without a connection once installed.",
        "start_url": "codeplug/",
        "scope": "./",
        "display": "standalone",
        "background_color": "#14161a",
        "theme_color": "#14161a",
        "icons": [
            {"src": "static/img/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
            {"src": "static/img/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"},
        ],
    }
    (ROOT / "manifest.webmanifest").write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
    print("manifest.webmanifest")


def worker(entries):
    version = hashlib.sha256("\n".join(entries).encode()).hexdigest()[:10]
    body = f"""// SPDX-License-Identifier: MIT
// Generated by tools/make_pwa.py — the site's offline layer. Do not edit by hand: change the site and re-run it.
const VERSION = "{version}";
const CACHE = "dm32-site-" + VERSION;
const PRECACHE = {json.dumps(entries, indent=1)};

self.addEventListener("install", (e) => {{
	e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});

self.addEventListener("activate", (e) => {{
	e.waitUntil(caches.keys()
		.then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
		.then(() => self.clients.claim()));
}});

// Network first (a visit with a connection picks up the site's own updates, including the sync-firmware commits),
// the cache as the fallback that works with none. Versioned static (?v=) never changes: cache first.
self.addEventListener("fetch", (e) => {{
	const req = e.request;
	if (req.method !== "GET") return;
	const url = new URL(req.url);
	if (url.origin !== location.origin) return;
	if (url.search.includes("check=")) return;	// the editor's own freshness check
	const soft = req.mode === "navigate" || /\\.(json|bin|zip)$/.test(url.pathname) || url.pathname.endsWith("/");
	const net = fetch(req).then((r) => {{
		if (r.ok) caches.open(CACHE).then((c) => c.put(req, r.clone()));
		return r;
	}}).catch(() => null);
	const cacheHit = async () => {{
		let hit = await caches.match(req);
		if (!hit && req.mode === "navigate") hit = await caches.match(new Request(url.pathname + "index.html"));
		if (!hit && /\\.(json|zip)$/.test(url.pathname)) {{
			// a firmware or data file whose name changed with a release: try the directory's cached entries
			const dir = url.pathname.slice(0, url.pathname.lastIndexOf("/") + 1);
			const keys = await caches.keys();
			for (const k of keys) {{
				const store = await caches.open(k);
				for (const key of await store.keys()) {{
					if (key.url.startsWith(dir)) {{
						hit = await store.match(key);
						if (hit) break;
					}}
				}}
				if (hit) break;
			}}
		}}
		return hit;
	}};
	if (soft) e.respondWith(net.then((r) => r || cacheHit()));
	else e.respondWith(caches.match(req).then((hit) => hit || net));
}});
"""
    (ROOT / "sw.js").write_text(body, encoding="utf-8")
    print("sw.js version", version, f"({len(entries)} entries)")


if __name__ == "__main__":
    entries = precache_list()
    icons()
    manifest(entries)
    worker(entries)
